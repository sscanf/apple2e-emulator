VideoController::VideoController() {
    m_frameBuffer.fill(0);
}

VideoController::~VideoController() {}

bool VideoController::init(SDL_Window* window) {
    (void)window;  // Window is passed to render()
    return true;
}

void VideoController::setMode(VideoMode mode) {
    m_mode = mode;
}

void VideoController::setMemoryReadCallback(std::function<uint8_t(uint16_t)> cb) {
    m_memoryRead = cb;
}

void VideoController::setCursorVisible(bool visible) {
    m_cursorVisible = visible;
}

void VideoController::setCursorPosition(uint8_t row, uint8_t col) {
    m_cursorRow = row;
    m_cursorCol = col;
}

uint8_t VideoController::lookupChar(uint8_t ch) const {
    return ch;  // Character is already the ROM index
}

void VideoController::render(SDL_Renderer* renderer) {
    if (!renderer) return;

    SDL_SetRenderDrawColor(renderer, 0, 0, 0, 255);
    SDL_RenderClear(renderer);

    switch (m_mode) {
        case VideoMode::OFF:
            renderOff(renderer);
            break;
        case VideoMode::TEXT_40:
            renderText(renderer);
            break;
        case VideoMode::LORES:
            renderLores(renderer);
            break;
        case VideoMode::HIRES:
            renderHires(renderer);
            break;
        case VideoMode::TEXT_80:
            renderText(renderer);  // 80-col text similar to 40-col
            break;
        case VideoMode::COLOR_HIRES:
            renderColorHires(renderer);
            break;
        case VideoMode::DOUBLE_HIRES:
            renderHires(renderer);  // Simplified
            break;
    }

    SDL_RenderPresent(renderer);
}

void VideoController::renderOff(SDL_Renderer* renderer) {
    // Black screen
    SDL_SetRenderDrawColor(renderer, 0, 0, 0, 255);
    SDL_RenderClear(renderer);
}

void VideoController::renderText(SDL_Renderer* renderer) {
    // 40-column text mode: 40 cols x 24 rows
    // Display memory at $0400-$07DF (page 1) and $07E0-$0BDF (page 2)
    // Each character is 6x8 pixels, displayed at ~14x16 with scaling

    const int cols = 40;
    const int rows = 24;
    const int charWidth = 14;
    const int charHeight = 16;
    const int startX = 20;
    const int startY = 10;

    // Clear to black
    SDL_SetRenderDrawColor(renderer, 0, 0, 0, 255);
    SDL_RenderFillRect(renderer, nullptr);

    // Render each character
    for (int row = 0; row < rows; row++) {
        for (int col = 0; col < cols; col++) {
            // Apple II text memory: $0400-$058F (page 1, 24x40)
            uint16_t addr = 0x0400 + row * 40 + col;

            if (!m_memoryRead) continue;

            uint8_t ch = m_memoryRead(addr);

            // Get character pattern from ROM
            uint8_t romIndex = lookupChar(ch);

            // Draw character
            int x = startX + col * charWidth;
            int y = startY + row * charHeight;

            for (int py = 0; py < 8; py++) {
                if (py >= 8) break;
                uint8_t pattern = kCharacterROM[romIndex][py];

                for (int px = 0; px < 6; px++) {
                    if (pattern & 0x80) {
                        // White pixel
                        SDL_SetRenderDrawColor(renderer, 0xAA, 0xAA, 0xAA, 255);
                        SDL_RenderDrawLine(renderer,
                            x + px * 2, y + py * 2,
                            x + (px + 1) * 2, y + py * 2);
                    }
                    pattern <<= 1;
                }
            }

            // Draw cursor
            if (m_cursorVisible && row == m_cursorRow && col == m_cursorCol) {
                SDL_SetRenderDrawColor(renderer, 0xAA, 0xAA, 0xAA, 255);
                SDL_RenderDrawLine(renderer, x, y + charHeight - 2,
                    x + charWidth, y + charHeight - 2);
            }
        }
    }
}

void VideoController::renderLores(SDL_Renderer* renderer) {
    // Lo-res: 160x192, 16 colors
    // Display memory at $0400-$0BDF
    // Each line is 40 bytes (320 bits), but only 160 pixels

    const int width = 160;
    const int height = 192;
    const int scale = 3;  // Scale up for visibility

    // Clear to black
    SDL_SetRenderDrawColor(renderer, 0, 0, 0, 255);
    SDL_RenderFillRect(renderer, nullptr);

    if (!m_memoryRead) return;

    // Lo-res: 40 bytes per line, each byte = 8 pixels
    // Colors determined by bit patterns
    for (int y = 0; y < height; y++) {
        int page = (y < 96) ? 0 : 1;
        int lineInPage = y % 96;
        uint16_t addr = 0x0400 + page * 0x0400 + lineInPage * 40;

        for (int x = 0; x < width; x += 2) {
            uint8_t byte = m_memoryRead(addr + x / 2);

            // Each byte represents 2 pixels (4 bits per pixel)
            uint8_t colorIdx1 = (byte >> 4) & 0x0F;
            uint8_t colorIdx2 = byte & 0x0F;

            uint32_t color1 = kColors[colorIdx1];
            uint32_t color2 = kColors[colorIdx2];

            SDL_SetRenderDrawColor(renderer,
                (color1 >> 16) & 0xFF,
                (color1 >> 8) & 0xFF,
                color1 & 0xFF, 255);
            SDL_RenderDrawLine(renderer,
                x * scale, y * scale,
                (x + 1) * scale, y * scale);

            if (x + 1 < width) {
                SDL_SetRenderDrawColor(renderer,
                    (color2 >> 16) & 0xFF,
                    (color2 >> 8) & 0xFF,
                    color2 & 0xFF, 255);
                SDL_RenderDrawLine(renderer,
                    (x + 1) * scale, y * scale,
                    (x + 2) * scale, y * scale);
            }
        }
    }
}

void VideoController::renderHires(SDL_Renderer* renderer) {
    // Hi-res: 560x192, 6 colors
    // Display memory at $2000-$27DF (page 1) or $2800-$2BDF (page 2)
    // Each line is 80 bytes (640 bits), but only 560 pixels

    const int width = 560;
    const int height = 192;
    const int scale = 1;

    // Clear to black
    SDL_SetRenderDrawColor(renderer, 0, 0, 0, 255);
    SDL_RenderFillRect(renderer, nullptr);

    if (!m_memoryRead) return;

    for (int y = 0; y < height; y++) {
        int page = (y < 96) ? 0 : 1;
        int lineInPage = y % 96;
        uint16_t addr = 0x2000 + page * 0x0800 + lineInPage * 80;

        for (int x = 0; x < width; x++) {
            uint8_t byte = m_memoryRead(addr + x / 8);
            uint8_t bit = 7 - (x % 8);
            bool pixel = byte & (1 << bit);

            // Hi-res colors alternate based on bit position
            uint8_t colorIdx;
            if (pixel) {
                // Alternating colors based on column
                colorIdx = ((x / 8) % 2 == 0) ? 3 : 5;  // Light gray or white
            } else {
                colorIdx = 0;  // Black
            }

            uint32_t color = kHiresColors[colorIdx];
            SDL_SetRenderDrawColor(renderer,
                (color >> 16) & 0xFF,
                (color >> 8) & 0xFF,
                color & 0xFF, 255);
            SDL_RenderDrawPoint(renderer, x * scale, y * scale);
        }
    }
}

void VideoController::renderColorHires(SDL_Renderer* renderer) {
    // Color hi-res: same as hi-res but with color information
    // Simplified: use lo-res colors for hi-res display
    renderHires(renderer);
}

